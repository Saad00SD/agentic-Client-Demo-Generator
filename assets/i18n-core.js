/* ---------- the layered lookup ----------
   app.js reads DICTS and PATTERNS and knows nothing about which
   language or which manufacturer it is running. The core seeds both;
   a build layers its own strings on top through registerI18n. A build
   key overrides a core key of the same English string, which is how a
   manufacturer renames a shared concept without forking the core. */
const DICTS    = {};
const PATTERNS = {};

LANGS.forEach(l => {
  if (l.code === 'en') return;
  DICTS[l.code]    = Object.assign(Object.create(null), CORE[l.code] || {});
  PATTERNS[l.code] = (CORE_PATTERNS[l.code] || []).slice();
});

function registerI18n(dicts, patterns) {
  Object.entries(dicts || {}).forEach(([code, map]) => {
    if (!DICTS[code]) DICTS[code] = Object.create(null);
    Object.assign(DICTS[code], map);
  });
  /* build rules are tried before core rules, so a build can special-case
     a string the core would otherwise catch */
  Object.entries(patterns || {}).forEach(([code, list]) => {
    if (!PATTERNS[code]) PATTERNS[code] = [];
    PATTERNS[code] = list.concat(PATTERNS[code]);
  });
}
